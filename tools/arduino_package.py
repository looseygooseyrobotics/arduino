"""Build the Loosey Goosey Robotics Arduino boards package (lgr/) and its Boards Manager index.

    python tools/arduino_package.py platform   # regenerate lgr/platform.txt from the installed Pico core
    python tools/arduino_package.py install    # copy the package into the sketchbook, to try it without a release
    python tools/arduino_package.py release    # write lgr-rp2040-<version>.zip and package_lgr_index.json into site/

The package borrows the Raspberry Pi Pico core (earlephilhower/arduino-pico) through `build.core=rp2040:rp2040`. When a
board borrows a core, arduino-cli uses the core's platform.txt but sets {runtime.platform.path} to this package, so
platform.txt is the core's own with every {runtime.platform.path} swapped for {build.core.platform.path}, and without
the discovery lines (the core's own discovery finds the board's BOOTSEL drive). That ties the package to one core
version (CORE_VERSION); the variant stops the build on any other.

The package bundles the LGR library (lgr/libraries/LGR) and copies of Pico PIO USB and Adafruit NeoPixel from
the sketchbook's libraries folder at the versions in BUNDLED. TinyUSB comes with the core. The index lists this
package and the core's own entry with its tools, so users add one Boards Manager URL, then install "Raspberry Pi
Pico/RP2040/RP2350" and "Loosey Goosey Robotics".

The index and the zips are served from https://arduino.looseygooseyrobotics.com by GitHub Pages, from this
repository's gh-pages branch. site/ is that branch checked out as a worktree (`git worktree add site gh-pages`). To
publish a release: bump VERSION, run `release`, then commit and push site/. The index keeps every earlier version, so a
release never removes one.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "lgr"
SITE = ROOT / "site"
BUILD = ROOT / "build"

VERSION = "0.1.0"
CORE_VERSION = "6.3.2"
BUNDLED = {"Pico_PIO_USB": "0.7.3", "Adafruit_NeoPixel": "1.15.5"}
SITE_URL = "https://arduino.looseygooseyrobotics.com"
WEBSITE = "https://looseygooseyrobotics.com"

ARDUINO15 = Path(os.environ.get("LOCALAPPDATA", Path.home() / ".arduino15")) / "Arduino15"
SKETCHBOOK = Path.home() / "Documents/Arduino"


def core_dir():
    d = ARDUINO15 / "packages/rp2040/hardware/rp2040" / CORE_VERSION
    if not d.is_dir():
        sys.exit(f"the Pico core {CORE_VERSION} isn't installed at {d}")
    return d


def platform():
    src = (core_dir() / "platform.txt").read_text(encoding="utf-8")
    out = [f"# Generated by tools/arduino_package.py from the Raspberry Pi Pico core {CORE_VERSION}'s platform.txt. Don't edit.",
           ""]
    for line in src.splitlines():
        if re.match(r"(pluggable_)?discovery\.rp2040\.", line):
            continue
        if line.startswith("name="):
            line = "name=Loosey Goosey Robotics"
        elif line.startswith("version="):
            line = f"version={VERSION}"
        out.append(line.replace("{runtime.platform.path}", "{build.core.platform.path}"))
    (SRC / "platform.txt").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {SRC / 'platform.txt'}")


def stage(dest):
    """The package as it installs: lgr/ plus the bundled libraries."""
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(SRC, dest)
    for name, version in BUNDLED.items():
        lib = SKETCHBOOK / "libraries" / name
        props = (lib / "library.properties").read_text(encoding="utf-8")
        found = re.search(r"^version=(.*)$", props, re.M).group(1).strip()
        if found != version:
            sys.exit(f"{lib} is {found}; BUNDLED wants {version}")
        shutil.copytree(lib, dest / "libraries" / name, ignore=shutil.ignore_patterns(".git*", ".github"))


def install():
    dest = SKETCHBOOK / "hardware/lgr/rp2040"
    stage(dest)
    print(f"installed in {dest}; restart the IDE and pick Tools > Board > Loosey Goosey Robotics > goosebrain")


def release(site):
    name = f"lgr-rp2040-{VERSION}.zip"
    archive = site / name
    index_path = site / "package_lgr_index.json"
    if archive.exists():
        sys.exit(f"{archive} is already published; bump VERSION")
    previous = []
    if index_path.exists():
        old = json.loads(index_path.read_text(encoding="utf-8"))
        previous = next(p for p in old["packages"] if p["name"] == "lgr")["platforms"]
    staged = BUILD / "stage" / f"lgr-rp2040-{VERSION}"
    stage(staged)
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(staged.rglob("*")):
            z.write(p, p.relative_to(staged.parent).as_posix())
    data = archive.read_bytes()

    core_index = json.loads((ARDUINO15 / "package_rp2040_index.json").read_text(encoding="utf-8"))
    rp2040 = next(p for p in core_index["packages"] if p["name"] == "rp2040")
    core = next(p for p in rp2040["platforms"] if p["version"] == CORE_VERSION)
    deps = core["toolsDependencies"]
    tools = [t for t in rp2040["tools"] if any(t["name"] == d["name"] and t["version"] == d["version"] for d in deps)]

    index = {"packages": [
        {
            "name": "lgr",
            "maintainer": "Loosey Goosey Robotics",
            "websiteURL": WEBSITE,
            "email": "",
            "help": {"online": WEBSITE},
            "platforms": [{
                "name": "Loosey Goosey Robotics",
                "architecture": "rp2040",
                "version": VERSION,
                "category": "Contributed",
                "url": f"{SITE_URL}/{name}",
                "archiveFileName": name,
                "checksum": "SHA-256:" + hashlib.sha256(data).hexdigest(),
                "size": str(len(data)),
                "help": {"online": WEBSITE},
                "boards": [{"name": "goosebrain"}],
                "toolsDependencies": deps,
            }] + [p for p in previous if p["version"] != VERSION],
            "tools": [],
        },
        # the core this package borrows, so one URL is enough
        {**{k: v for k, v in rp2040.items() if k not in ("platforms", "tools")}, "platforms": [core], "tools": tools},
    ]}
    index_path.write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {archive} ({len(data)} bytes) and {index_path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("step", choices=["platform", "install", "release"])
    ap.add_argument("--site", type=Path, default=SITE, help="release: where to write (default site/, the gh-pages worktree)")
    args = ap.parse_args()
    if args.step == "release":
        if not args.site.is_dir():
            ap.error(f"{args.site} doesn't exist; run `git worktree add site gh-pages` first")
        release(args.site)
    else:
        {"platform": platform, "install": install}[args.step]()


if __name__ == "__main__":
    main()
